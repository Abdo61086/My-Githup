`timescale 1ns/1ps
module CLK_DIV_tb();

/////////////////////////////////////////////////////////////
/////////////////////// Parameter ///////////////////////////
/////////////////////////////////////////////////////////////
parameter CLK_PERIOD = 10 ;



 reg i_ref_clk_tb;
 reg i_rst_n_tb;
 reg i_clk_en_tb;
 reg [7:0] i_div_ratio_tb;
 wire o_div_clk_tb;

/////////////////////////////////////////////////////////////
/////////////////////// inistantiation //////////////////////
/////////////////////////////////////////////////////////////

CLK_DIV DUT 
         (
            .i_ref_clk(i_ref_clk_tb),
            .i_rst_n(i_rst_n_tb),
            .i_clk_en(i_clk_en_tb),
            .i_div_ratio(i_div_ratio_tb),
            .o_div_clk(o_div_clk_tb)
         );

/////////////////////////////////////////////////////////////
/////////////////////// Clk definition //////////////////////
/////////////////////////////////////////////////////////////

always #(CLK_PERIOD) i_ref_clk_tb = ~i_ref_clk_tb;

/////////////////////////////////////////////////////////////
/////////////////////// initialization //////////////////////
/////////////////////////////////////////////////////////////

task initialization();
  begin
    i_ref_clk_tb   =  0;
    i_clk_en_tb    =  0;
    i_div_ratio_tb = 'b0;
    i_rst_n_tb     =  1;
  end
endtask


/////////////////////////////////////////////////////////////
/////////////////////// Reset ///////////////////////////////
/////////////////////////////////////////////////////////////

task RESET();
  begin
    #(CLK_PERIOD)
    i_rst_n_tb = 0;
    #(CLK_PERIOD)
    i_rst_n_tb = 1;
    #(CLK_PERIOD);
  end
endtask

/////////////////////////////////////////////////////////////
/////////////////////// initial block ///////////////////////
/////////////////////////////////////////////////////////////

initial begin
  initialization();
  RESET();
//try odd number 
  i_div_ratio_tb = 8'd7;
  i_clk_en_tb = 1;
  #(100*CLK_PERIOD);
//try even and change number of division
  i_div_ratio_tb = 8'd8;
   #(100*CLK_PERIOD);
   i_div_ratio_tb = 8'd11;
   #(100*CLK_PERIOD);
   i_div_ratio_tb = 8'd6;
   #(100*CLK_PERIOD);
   i_div_ratio_tb = 8'd20;
   #(100*CLK_PERIOD);
//try number 1
   i_div_ratio_tb = 8'd1;
   #(100*CLK_PERIOD);
//try number 0
   i_div_ratio_tb = 8'd0;
   #(100*CLK_PERIOD);
  $stop;


end



endmodule